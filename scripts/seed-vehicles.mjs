// ── Main ─────────────────────────────────────────────────────────────────────
const [,, email, password] = process.argv;
if (!email || !password) {
  console.error('Usage: node scripts/seed-vehicles.mjs <email> <password>');
  process.exit(1);
}

const supabase = createClient(SUPABASE_URL, SUPABASE_ANON);

console.log(`\nSigning in as ${email}…`);
const { error: authErr } = await supabase.auth.signInWithPassword({ email, password });
if (authErr) { console.error('Auth failed:', authErr.message); process.exit(1); }
console.log('✓ Signed in.\n');

// Resolve Shop 1 ID
const { data: shops, error: shopErr } = await supabase
  .from('shops')
  .select('id, name')
  .eq('slug', SHOP1_SLUG)
  .limit(1);
if (shopErr || !shops?.length) {
  console.error('Could not find Shop 1 (d1-imports):', shopErr?.message ?? 'not found');
  process.exit(1);
}
const shopId = shops[0].id;
console.log(`Shop 1: ${shops[0].name} → ${shopId}\n`);

// Insert rows
const rows = RECORDS.map(r => ({
  shop_id:          shopId,
  customer_id:      null,
  label:            r.label,
  vin:              r.vin ?? '',
  plate:            r.plate ?? '',
  status:           r.status,
  trim:             '',
  engine:           '',
  transmission:     '',
  mileage:          '',
  recommendation:   '',
  make:             r.make,
  model:            r.model,
  year:             r.year,
  fuel_type:        r.fuel_type,
  issues:           r.issues,
  damage_intake:    r.damage_intake,
  issues_resolved:  r.issues_resolved,
  parts_exchanged:  r.parts_exchanged,
  parts_needed:     r.parts_needed,
  flat_rate_lak:    r.flat_rate_lak,
  image_ids:        r.image_ids,
  tech_pay_entries: r.tech_pay_entries,
  assigned_tech:    r.assigned_tech,
  date_received:    r.date_received,
}));

console.log(`Inserting ${rows.length} vehicle / service records…`);
const { error: insertErr } = await supabase.from('vehicles').insert(rows);
if (insertErr) {
  console.error('Insert failed:', insertErr.message);
  console.error('Hint:', insertErr.hint ?? '—');
  console.error('\nMake sure you ran the SQL migration first:\n  supabase/migration_vehicles_service_records.sql');
  process.exit(1);
}

console.log(`\n✓ Done! ${rows.length} records inserted into ${shops[0].name}.\n`);
console.log('Status breakdown:');
const byStatus = {};
rows.forEach(r => { byStatus[r.status] = (byStatus[r.status] ?? 0) + 1; });
Object.entries(byStatus).forEach(([s, n]) => console.log(`  ${s}: ${n}`));
