/**
 * lib/intelligence-bus/event-types.ts
 *
 * Strongly typed event contracts for the Redline Intelligence Bus.
 * Every event extends RibBaseEvent which provides the full causality envelope.
 * No `any` types anywhere in this file.
 */

// ---------------------------------------------------------------------------
// Envelope constants
// ---------------------------------------------------------------------------

export const MAX_EVENT_DEPTH = 10;
export const RIB_SCHEMA_VERSION = '1.0' as const;

// ---------------------------------------------------------------------------
// Base envelope — required on every RIB event
// ---------------------------------------------------------------------------

export interface RibBaseEvent {
  /** Globally unique event identifier (UUID v4), auto-generated by publisher */
  eventId: string;
  /** Discriminator — narrows to a concrete event type */
  eventType: RibEventType;
  /** Event schema version for forward-compatibility */
  schemaVersion: typeof RIB_SCHEMA_VERSION;

  // -- Causality --
  /** When the business event actually occurred (caller-provided, ISO-8601) */
  occurredAt: string;
  /** Groups all events in the same end-to-end workflow (trace ID) */
  correlationId: string;
  /** eventId that directly caused this event; null for root (user-initiated) events */
  causationId: string | null;
  /** 0 for root events; increments once per derived event in a causal chain */
  eventDepth: number;
  /** Module that published this event (e.g. 'vehicle_health', 'diagnostic_orchestrator') */
  originModule: string;

  // -- Tenant --
  /** Multi-tenant organization identifier */
  organizationId: string;
  /** Shop this event belongs to (UUID) */
  shopId: string;

  // -- Actor --
  /** Technician who triggered the action; null for system-generated events */
  technicianId: string | null;
  /** Vehicle involved in this event; null when not vehicle-specific */
  vehicleId: string | null;
  /** Diagnostic session context; null when not session-specific */
  diagnosticSessionId: string | null;
}

