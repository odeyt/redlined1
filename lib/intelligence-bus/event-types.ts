// ---------------------------------------------------------------------------
// Payload reference type — use for large or binary data
// ---------------------------------------------------------------------------

/** Reference to an externally stored asset. Never embed binary data inline. */
export interface RibPayloadReference {
  storageProvider: 'supabase_storage' | 's3' | 'local';
  objectKey: string;
  contentType: string;
  sizeBytes: number;
  checksum: string;
  schemaVersion: string;
  accessClassification: 'shop_private' | 'tenant_private' | 'global_anonymized';
}

